<?php

declare(strict_types=1);

namespace App\Tests\Integration\Service\Photo;

use App\Entity\Application\Enums\ImageVariant;
use App\Entity\Photo\Photo;
use App\Service\Photo\PhotoApiUrlBuilder;
use App\Tests\Integration\DatabaseTestCase;
use Symfony\Component\HttpFoundation\Request;

use function str_contains;
use function str_ends_with;
use function str_starts_with;

/**
 * The absolute addresses an API consumer is handed. They are built against the host the request came in on, because
 * the same deployment answers to more than one name, and they fall back to a relative address when there is no request
 * (a worker, a console command).
 */
final class PhotoApiUrlBuilderTest extends DatabaseTestCase
{
    private const string HOST = 'https://radix.example.test';

    public function testAPhotoUrlIsAbsoluteOnTheRequestHost(): void
    {
        $photo = $this->photo();
        $this->pushRequest();

        self::assertSame(
            self::HOST . '/api/photos/' . $photo->id . '/image/w640',
            $this->builder()->photoUrl(
                $photo,
                ImageVariant::W640,
            ),
        );
    }

    public function testACoverUrlNamesTheAlbumAndTheVariant(): void
    {
        $this->pushRequest();

        self::assertSame(
            self::HOST . '/api/photos/albums/5/cover/cover',
            $this->builder()->albumCoverUrl(
                5,
                ImageVariant::Cover,
            ),
        );
    }

    /**
     * A stored file goes through the image pipeline, so a private namespace ends up signed.
     */
    public function testAStoredUrlIsTheSignedServingUrl(): void
    {
        $this->pushRequest();

        $url = $this->builder()->storedUrl(
            'photos/albums/5/abc.jpg',
            ImageVariant::W640,
        );

        self::assertTrue(str_starts_with($url, self::HOST . '/img/w640/photos/albums/5/abc.jpg'));
        self::assertTrue(str_contains($url, '?expires='));
        self::assertTrue(str_contains($url, '&signature='));
    }

    public function testTheAlbumPhotoCollectionUrlIsTheApiOperation(): void
    {
        $this->pushRequest();

        // Generated by the router rather than assembled here, so only the operation's own path is fixed.
        $url = $this->builder()->albumPhotosUrl(5);

        self::assertTrue(str_starts_with($url, 'http'));
        self::assertTrue(str_ends_with($url, '/api/photos/albums/5/photos'));
    }

    /**
     * Without a request there is no host to name, so the address stays relative rather than guessing one.
     */
    public function testWithoutARequestTheAddressesStayRelative(): void
    {
        $stack = self::getContainer()->get('request_stack');
        self::assertNull($stack->getCurrentRequest());

        self::assertSame(
            '/api/photos/albums/7/cover/cover',
            $this->builder()->albumCoverUrl(
                7,
                ImageVariant::Cover,
            ),
        );
    }

    private function builder(): PhotoApiUrlBuilder
    {
        return self::getContainer()->get(PhotoApiUrlBuilder::class);
    }

    private function pushRequest(): void
    {
        $stack = self::getContainer()->get('request_stack');
        $request = Request::create(self::HOST . '/api/photos/albums');
        $stack->push($request);
    }

    private function photo(): Photo
    {
        $repository = $this->entityManager->getRepository(Photo::class);
        $photo = $repository->findOneBy([]);
        self::assertInstanceOf(
            Photo::class,
            $photo,
            'The seed is expected to contain a photo.',
        );

        return $photo;
    }
}
